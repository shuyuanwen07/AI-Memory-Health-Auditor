"""Build separate readable blind-review JSON for four-strategy B answers.

No automatic judgments, strategy labels, or private answer identities appear
in reviewer packets. No human decisions are generated by this script.
"""
import hashlib
import json
import secrets
from pathlib import Path


def canonical(value):return json.dumps(value,sort_keys=True,ensure_ascii=False,separators=(',',':')).encode()


def prepare(state,protocol,addendum):
    if state.get('status')!='complete_automatic_collection' or not addendum.get('same_question_set_verified'):
        raise ValueError('A complete and prechecked four-strategy collection is required')
    strategies=set(protocol['target']['memory_strategies'])
    if strategies!={'weak_first_hit','strong_rule_based','scope_aware','temporal_importance'}:
        raise ValueError('Unexpected strategy set')
    source=json.loads(Path('datasets/phase4-candidate-v1/source-histories.json').read_bytes())
    if hashlib.sha256(Path('datasets/phase4-candidate-v1/source-histories.json').read_bytes()).hexdigest()!=protocol['followup_source_sha256']:
        raise ValueError('Synthetic source changed')
    by_history={h['scenario_id']:h for h in source}
    questions={};answers=[];mapping={}
    for scenario in state['scenarios']:
        hid=scenario['scenario_id'];history=by_history[hid];runs=scenario['runs']
        cells={(r['strategy'],r['repetition']) for r in runs}
        if cells!={(s,n) for s in strategies for n in (1,2,3)} or len(runs)!=12:
            raise ValueError('Missing or duplicated strategy repeat')
        for run in runs:
            tests={t['test_id']:t for t in run['tests']}
            responses=run.get('responses');evaluations=run.get('evaluations')
            if len(tests)!=4 or not isinstance(responses,list) or len(responses)!=4 or not isinstance(evaluations,list) or len(evaluations)!=4:
                raise ValueError('Every run needs four saved answers and assessments')
            evals={e['response_id']:e for e in evaluations}
            if (len(evals)!=4 or {r['test_id'] for r in responses}!=set(tests)
                    or {r['response_id'] for r in responses}!=set(evals)):
                raise ValueError('Saved answers and assessments must uniquely match the four questions')
            for response in responses:
                test=tests[response['test_id']];evaluation=evals[response['response_id']]
                content={'history_id':hid,'question':test['prompt'],'expected_behavior':test['expected_behavior'],
                         'source_message_ids':test['supporting_memory_ids']}
                qid='Q'+hashlib.sha256(canonical(content)).hexdigest()[:20]
                questions.setdefault(qid,{'question_id':qid,'history_id':hid,'question':test['prompt'],
                    'expected_behavior':test['expected_behavior']})
                blind=secrets.token_hex(16)
                if blind in mapping:raise ValueError('Random identity collision')
                answer=response['response_text'];digest=hashlib.sha256(answer.encode()).hexdigest()
                answers.append({'blind_id':blind,'question_id':qid,'answer':answer,'answer_sha256':digest})
                mapping[blind]={'history_id':hid,'strategy':run['strategy'],'repetition':run['repetition'],
                    'run_id':run['run_id'],'test_id':test['test_id'],'response_id':response['response_id'],
                    'dimension':test['dimension'],'answer_sha256':digest,'automatic_evaluation':evaluation}
    if len(questions)!=12 or len(answers)!=144 or len(mapping)!=144:
        raise ValueError('Expected 12 shared questions and 144 distinct answers')
    histories=[{'history_id':hid,'source_messages':by_history[hid]['messages']} for hid in sorted(by_history)]
    secrets.SystemRandom().shuffle(answers)
    material={'format':'b-four-strategy-blind-material-v1','histories':histories,
              'questions':list(questions.values()),'answers':answers}
    material_sha=hashlib.sha256(canonical(material)).hexdigest()
    reviewers=[]
    for slot in (1,2):
        reviewers.append({'format':'b-four-strategy-human-review-v1','reviewer_slot':slot,
            'material_sha256':material_sha,'reviewer_declaration':{'reviewer_label':None,'completed_by_human':None,
                'completed_independently':None,'seen_current_automatic_results':None,'seen_other_review':None,
                'used_ai_assistance':None,'previously_seen_prior_b_results':None},
            'histories':material['histories'],'questions':material['questions'],'answers':material['answers'],
            'question_reviews':[{'question_id':q['question_id'],'valid':None,'note':''} for q in material['questions']],
            'answer_reviews':[{'blind_id':a['blind_id'],'verdict':None,'failure_dimension':None,'note':''} for a in answers]})
    return reviewers,{'format':'b-four-strategy-private-key-v1','material_sha256':material_sha,'mapping':mapping}


def main():
    root=Path('output/proposal-delivery/experiment-b-four-strategy-20261029-v1')
    state=json.loads((root/'B-live.json').read_bytes());protocol=json.loads((root/'protocol.json').read_bytes())
    addendum=json.loads((root/'execution-addendum.json').read_bytes())
    reviews,key=prepare(state,protocol,addendum)
    out=root/'human-review';out.mkdir(mode=0o700,exist_ok=False)
    material={'format':'b-four-strategy-blind-material-v1','histories':reviews[0]['histories'],
              'questions':reviews[0]['questions'],'answers':reviews[0]['answers']}
    if hashlib.sha256(canonical(material)).hexdigest()!=key['material_sha256']:
        raise ValueError('Private material digest changed')
    for i,review in enumerate(reviews,1):
        with (out/f'reviewer-{i}.json').open('x',encoding='utf8') as f:json.dump(review,f,ensure_ascii=False,indent=2);f.write('\n')
    with (root/'private-review-key.json').open('x',encoding='utf8') as f:json.dump(key,f,ensure_ascii=False,indent=2);f.write('\n')
    with (root/'private-review-material.json').open('x',encoding='utf8') as f:json.dump(material,f,ensure_ascii=False,indent=2);f.write('\n')
    print(json.dumps({'reviewers':2,'questions':12,'answers_per_reviewer':144,'human_decisions_created':False}))


if __name__=='__main__':main()
