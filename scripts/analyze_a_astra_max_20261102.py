"""Reconcile independent MAX reviews of the frozen method-comparison answers."""
from collections import Counter
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'output/proposal-delivery/a-astra-max-retest-20261101-v2'


def read(path):return json.loads(path.read_text())


def main():
    material=read(BASE/'blind-review/material.json')
    mapping={x['review_id']:x for x in read(BASE/'private-review-key.json')['mapping']}
    judges=[read(BASE/f'review-max/reviewer-{n}.review.json') for n in (1,2)]
    maps=[{x['review_id']:x for x in j['items']} for j in judges]
    if len(mapping)!=48 or any(set(m)!=set(mapping) for m in maps):raise ValueError('A review identities differ')
    source_by_id={s['source_id']:s for s in material['sources']}
    input_by_id={x['review_id']:x for x in material['items']}
    candidates={d['defect_id'] for s in material['sources'] for d in s['candidate_failure_patterns']}
    rows=[]
    for rid,key in mapping.items():
        pair=[m[rid] for m in maps]
        valid=all(x.get('question_validity')=='valid' and x.get('reference_validity')=='valid' for x in pair)
        verdicts=[x['answer_verdict'] for x in pair]
        verdict=verdicts[0] if valid and verdicts[0]==verdicts[1] else 'uncertain'
        allowed={x['defect_id'] for x in source_by_id[input_by_id[rid]['source_id']]['candidate_failure_patterns']}
        observed=[set(x.get('detected_defect_ids') or []) for x in pair]
        if any(not x<=allowed for x in observed):raise ValueError('A defect mapped outside source inventory')
        confirmed=observed[0]&observed[1]
        if confirmed and verdict!='fail':raise ValueError('Defect mapping contradicts answer verdict')
        rows.append({**key,'verdict':verdict,'question_reference_valid':valid,'judgments':verdicts,
            'detected_defect_ids':sorted(confirmed),'disputed_defect_ids':sorted(observed[0]^observed[1]),
            'safe_but_incomplete':all(x.get('safe_but_incomplete') is True for x in pair),
            'outside_inventory_errors':[x.get('outside_inventory_errors',[]) for x in pair],
            'reasons':[x.get('reason') for x in pair]})
    methods=[]
    for name in ('Direct questions','Fixed templates','Contextual/indirect Auditor tests'):
        selected=[x for x in rows if x['method']==name]
        if not selected:
            continue
        counts=Counter(x['verdict'] for x in selected)
        defects={d for x in selected for d in x['detected_defect_ids']}
        methods.append({'label':name,'planned_answers':16,'answered':len(selected),'pass':counts['pass'],'fail':counts['fail'],
            'unresolved':counts['uncertain'],'safe_but_incomplete':sum(x['safe_but_incomplete'] for x in selected),
            'candidate_patterns_exposed':len(defects),'candidate_pattern_pool':len(candidates),'matched_ids':sorted(defects),
            'disputed_mapping_answers':sum(bool(x['disputed_defect_ids']) for x in selected)})
    if sum(m['answered'] for m in methods)!=48:
        names=sorted({x['method'] for x in rows});raise ValueError(f'Unexpected method labels: {names}')
    result={'format':'a-astra-max-retest-v2','provider':'openai','model':'gpt-6-astra','reasoning_effort':'max',
        'review_model':'gpt-6-astra','review_reasoning_effort':'max','review_status':'ai_reviewed','human_confirmation_pending':True,
        'histories':4,'planned_answers':48,'answered':48,'methods':methods,'items':rows,
        'review_sha256':[hashlib.sha256((BASE/f'review-max/reviewer-{n}.review.json').read_bytes()).hexdigest() for n in (1,2)],
        'limitations':['One repetition and four related synthetic scenarios.',
            'Candidate patterns are potential failures, not proof every pattern occurred.',
            'Strict factual completeness and safe but incomplete behavior are distinct.',
            'Unmapped failures and disputed mappings are retained, not forced into the inventory.',
            'Fixed questions were generated by deterministic code; only model-backed target calls require Astra max.']}
    (BASE/'analysis.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    public={k:v for k,v in result.items() if k!='items'}
    (ROOT/'frontend/public/reports/a-astra-max-retest-v2.json').write_text(json.dumps(public,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(methods))


if __name__=='__main__':main()
